#!/usr/bin/env python3
"""Render README.md (and the Hugging Face Space page) from their templates.

Every number in the README is a ``{{macro}}`` filled from
``results/tables/headline.json``, which ``experiments/make_numbers.py`` also
turns into the manuscript's ``paper/numbers.tex``. The README and the paper can
therefore never disagree, and re-running the studies updates both.

    python experiments/make_readme.py            # writes README.md
    python experiments/make_readme.py --check    # exit 1 if README.md is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADLINE = ROOT / "results" / "tables" / "headline.json"
TARGETS = [  # (template, output)
    (ROOT / "docs" / "README.template.md", ROOT / "README.md"),
    (ROOT / "hf" / "space" / "index.template.html", ROOT / "hf" / "space" / "index.html"),
    (ROOT / "hf" / "DATASET_CARD.template.md", ROOT / "hf" / "DATASET_CARD.md"),
]


def render(template: Path) -> str:
    numbers = json.loads(HEADLINE.read_text())
    text = template.read_text()
    missing: list[str] = []

    def fill(match: re.Match) -> str:
        key = match.group(1)
        value = numbers.get(key)
        if value is None or value == "??":
            missing.append(key)
            return "??"
        return value.replace(" ", ",") if re.fullmatch(r"\d{1,3}( \d{3})+", value) else value

    out = re.sub(r"\{\{([A-Za-z]+)\}\}", fill, text)
    if missing:
        sys.exit(f"{template.name} uses undefined numbers: " + ", ".join(sorted(set(missing))))
    banner = f"GENERATED by experiments/make_readme.py from {template.relative_to(ROOT)}: edit the template, not this file."
    if template.suffix == ".md":
        if out.startswith("---\n"):  # keep YAML front matter first (Hugging Face cards)
            end = out.index("\n---\n", 4) + 5
            return out[:end] + f"<!-- {banner} -->\n" + out[end:]
        return f"<!-- {banner} -->\n" + out
    return out.replace("<!doctype html>", f"<!doctype html>\n<!-- {banner} -->", 1)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for template, out in TARGETS:
        text = render(template)
        if args.check:
            if not out.exists() or out.read_text() != text:
                stale.append(out.name)
            continue
        out.write_text(text)
        print(f"{out.relative_to(ROOT)} written ({len(text.splitlines())} lines)")
    if stale:
        sys.exit("stale: " + ", ".join(stale))


if __name__ == "__main__":
    main()
